def get_portal_translator(locale: str | None) -> Callable[..., str]:
    """Return a translator function for the given locale."""
    lang = (locale or "en").lower().strip()
    if lang not in PORTAL_TRANSLATIONS:
        lang = "en"
    catalog = PORTAL_TRANSLATIONS[lang]
    fallback_catalog = PORTAL_TRANSLATIONS["en"]

    def _(key: str, default: str | None = None, **kwargs: Any) -> str:
        text = catalog.get(key)
        if text is None:
            text = fallback_catalog.get(key, default or key)
        if kwargs and text:
            try:
                text = text.format(**kwargs)
            except Exception:
                pass
        return text

    return _


def get_portal_i18n_dict(locale: str | None) -> dict[str, str]:
    """Return dictionary of translations for client-side JavaScript."""
    lang = (locale or "en").lower().strip()
    if lang not in PORTAL_TRANSLATIONS:
        lang = "en"
    return PORTAL_TRANSLATIONS[lang]
