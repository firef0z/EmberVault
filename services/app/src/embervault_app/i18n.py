def get_current_locale() -> str:
    """Determine the active locale for the current request.

    Priority:
    1. Query parameter ?lang=...
    2. Session['locale'] if set explicitly by user
    3. User browser's HTTP Accept-Language header
    4. Configured default locale (EMBERVAULT_DEFAULT_LOCALE or DB setting)
    5. Default fallback locale ('en')
    """
    if not has_request_context():
        return "en"

    # 1. Query parameter override
    lang_param = request.args.get("lang")
    if lang_param:
        clean_lang = lang_param.lower().strip()
        if clean_lang in SUPPORTED_LOCALES:
            session["locale"] = clean_lang
            return clean_lang

    # 2. Session override explicitly chosen by user
    if "locale" in session and session["locale"] in SUPPORTED_LOCALES:
        return str(session["locale"])

    # 3. HTTP Accept-Language header from user browser
    if request.accept_languages:
        # First check best_match
        best = request.accept_languages.best_match(list(SUPPORTED_LOCALES))
        if best:
            return best
        # Fallback to checking 2-letter language code prefix (e.g. 'de-DE' -> 'de', 'zh-CN' -> 'zh')
        for user_lang, _quality in request.accept_languages:
            prefix = user_lang.lower().split("-")[0].split("_")[0]
            if prefix in SUPPORTED_LOCALES:
                return prefix

    # 4. Configured default locale
    try:
        from flask import current_app

        store = current_app.config.get("SETTINGS_STORE")
        if store:
            configured = str(store.get_setting("default_locale") or "").strip().lower()
            if configured in SUPPORTED_LOCALES:
                return configured
    except Exception:
        pass

    # 5. Default fallback
    return "en"


def translate(key: str, default: str | None = None, /, **kwargs: Any) -> str:
    """Translate a message key to the current locale."""
    loc = (getattr(g, "locale", None) if has_request_context() else None) or get_current_locale()
    locale_dict = TRANSLATIONS.get(loc, TRANSLATIONS.get("en", TRANSLATIONS["it"]))
    fallback_dict = TRANSLATIONS.get("en", TRANSLATIONS["it"])
    text = locale_dict.get(key, fallback_dict.get(key, default or key))
    if kwargs and isinstance(text, str):
        for k, v in kwargs.items():
            text = text.replace(f"{{{k}}}", str(v))
    return text


def localize_proxies_activity(proxies: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Localize proxy activity strings returned by ExecutionRepository.get_run_proxies_activity."""
    if not proxies:
        return proxies
    result: list[dict[str, Any]] = []
    for p in proxies:
        item = dict(p)
        state = item.get("state")
        active_tasks = item.get("active_tasks") or []
        activity = str(item.get("activity") or "")
        if state == "disabled" or activity == "Disabilitato":
            item["activity"] = translate("proxy_activity_disabled")
        elif state == "offline" or activity == "Offline":
            item["activity"] = translate("proxy_activity_offline")
        elif state == "busy":
            if len(active_tasks) == 1:
                item["activity"] = translate(
                    "proxy_activity_running_single_tpl", task=active_tasks[0]
                )
            elif len(active_tasks) > 1:
                item["activity"] = translate(
                    "proxy_activity_running_multi_tpl",
                    tasks=", ".join(str(t) for t in active_tasks),
                )
            elif activity.startswith("Eseguendo task: "):
                item["activity"] = translate(
                    "proxy_activity_running_multi_tpl", tasks=activity[len("Eseguendo task: ") :]
                )
            elif activity.startswith("Eseguendo task "):
                item["activity"] = translate(
                    "proxy_activity_running_single_tpl", task=activity[len("Eseguendo task ") :]
                )
        elif state == "idle" or activity == "In attesa di task":
            item["activity"] = translate("proxy_activity_waiting_tasks")
        result.append(item)
    return result


def init_i18n(app: Flask) -> None:
    """Initialize Flask-Babel and Jinja translation helper functions."""
    babel.init_app(app, locale_selector=get_current_locale)

    @app.before_request
    def set_request_locale() -> None:
        g.locale = get_current_locale()

    @app.context_processor
    def inject_i18n() -> dict[str, Any]:
        return {
            "_": translate,
            "current_locale": getattr(g, "locale", "en"),
            "supported_locales": SUPPORTED_LOCALES,
        }
