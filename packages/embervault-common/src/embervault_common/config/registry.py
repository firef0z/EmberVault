def generate_env_example() -> str:
    """Generate the canonical content for .env.example based on CONFIG_REGISTRY."""
    lines: list[str] = [
        "# ============================================================================",
        "# EmberVault Configuration Template (.env.example)",
        "# Generated from CONFIG_REGISTRY. Do not edit manually.",
        "# ============================================================================",
        "",
    ]

    current_service = ""
    for key in CONFIG_REGISTRY:
        if key.service != current_service:
            current_service = key.service
            lines.append(f"# --- {current_service.upper()} SETTINGS ---")

        lines.append(f"# {key.description}")
        if key.overridable_from_gui:
            lines.append("# [Overridable da GUI]")
        if key.file_env_var:
            lines.append(f"# Supporta anche {key.file_env_var} per Docker Secrets")

        default_repr = ""
        if key.example:
            default_repr = key.example
        elif key.default is not None:
            default_repr = str(key.default)

        lines.append(f"{key.env_var}={default_repr}")
        lines.append("")

    return "\n".join(lines).strip() + "\n"


