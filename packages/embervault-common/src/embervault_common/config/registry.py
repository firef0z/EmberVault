    env_var: str
    service: str  # common, db, security, app, orchestrator, proxy
    type_name: str
    default: Any
    description: str
    example: str
    file_env_var: str | None = None
    overridable_from_gui: bool = False
    requires_restart: bool = False
    secret: bool = False


